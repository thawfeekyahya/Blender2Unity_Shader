using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace B2U
{
    public enum HlslPipeline { URP, BuiltIn }

    /// <summary>Writes a self-contained .shader file (URP Lit forward pass or Built-in surface shader).</summary>
    public static class HlslShaderWriter
    {
        static readonly Dictionary<ImplicitInput, string> ImplicitVars = new Dictionary<ImplicitInput, string>
        {
            { ImplicitInput.UV0, "b2u_uv0" }, { ImplicitInput.UV1, "b2u_uv1" },
            { ImplicitInput.NormalWS, "b2u_normalWS" }, { ImplicitInput.TangentWS, "b2u_tangentWS" },
            { ImplicitInput.BitangentWS, "b2u_bitangentWS" }, { ImplicitInput.ViewDirWS, "b2u_viewWS" },
            { ImplicitInput.PositionWS, "b2u_positionWS" }, { ImplicitInput.PositionOS, "b2u_positionOS" },
        };

        public static string Write(IRGraph g, HlslPipeline pipeline, string shaderName)
        {
            return pipeline == HlslPipeline.URP ? WriteUrp(g, shaderName) : WriteBuiltIn(g, shaderName);
        }

        // ------------------------------------------------------------------------------
        // Shared pieces
        // ------------------------------------------------------------------------------

        static string Var(IRNode n, string port) => $"n{n.Id}_{port}";

        static string Arg(IRInput i)
        {
            if (i.Link != null)
            {
                var v = Var(i.Link.Node, i.Link.Port);
                if (i.Link.Type == PortType.Float && i.Type != PortType.Float)
                    return $"({v}).{new string('x', (int)i.Type)}";
                if (i.Link.Type != PortType.Float && i.Type == PortType.Float) return $"({v}).x";
                return v;
            }
            if (i.Implicit != ImplicitInput.None) return ImplicitVars[i.Implicit];
            return Hlsl.Literal(i.Type, i.Constant);
        }

        static string Functions(IRGraph g)
        {
            var sb = new StringBuilder();
            sb.Append(HlslLibrary.Common).Append('\n');
            foreach (var n in g.Ordered())
                if (n.Kind == IRNodeKind.Function)
                    sb.Append(Hlsl.FunctionDefinition(n, "")).Append('\n');
            return sb.ToString();
        }

        /// <param name="sample">(texture, uvExpression) => float4 sample expression</param>
        static string GraphCode(IRGraph g, System.Func<IRTexture, string, string> sample, string indent)
        {
            var sb = new StringBuilder();
            foreach (var n in g.Ordered())
            {
                if (n.Kind == IRNodeKind.Texture)
                {
                    var uv = Arg(n.Inputs[0]);
                    sb.Append(indent).Append($"float4 n{n.Id}_tex = {sample(n.Texture, "(" + uv + ").xy")};\n");
                    sb.Append(indent).Append($"float3 {Var(n, "Color")} = n{n.Id}_tex.rgb;\n");
                    sb.Append(indent).Append($"float {Var(n, "Alpha")} = n{n.Id}_tex.a;\n");
                    continue;
                }
                foreach (var o in n.Outputs)
                    sb.Append(indent).Append($"{Hlsl.TypeName(o.Type)} {Var(n, o.Name)};\n");
                var args = n.Inputs.Select(Arg).Concat(n.Outputs.Select(o => Var(n, o.Name)));
                sb.Append(indent).Append($"{n.FunctionName}({string.Join(", ", args)});\n");
            }
            return sb.ToString();
        }

        static string Properties(IRGraph g)
        {
            var sb = new StringBuilder();
            foreach (var t in g.Textures)
                sb.Append($"        {t.PropertyName}(\"{Escape(t.DisplayName)}\", 2D) = \"white\" {{}}\n");
            sb.Append($"        _Cutoff(\"Alpha Cutoff\", Range(0, 1)) = {Hlsl.F(g.AlphaThreshold)}\n");
            return sb.ToString();
        }

        static string Escape(string s) => (s ?? "").Replace("\\", "/").Replace("\"", "'");

        // ------------------------------------------------------------------------------
        // URP
        // ------------------------------------------------------------------------------

        static string WriteUrp(IRGraph g, string shaderName)
        {
            var s = g.Surface;
            var sb = new StringBuilder();
            sb.Append($"// Generated by Blender to Unity Shader Converter from material '{g.MaterialName}'.\n");
            sb.Append("// Target: Universal Render Pipeline (12+).\n");
            sb.Append($"Shader \"{Escape(shaderName)}\"\n{{\n    Properties\n    {{\n");
            sb.Append(Properties(g));
            sb.Append("    }\n    SubShader\n    {\n");
            sb.Append(g.Transparent
                ? "        Tags { \"RenderType\"=\"Transparent\" \"Queue\"=\"Transparent\" \"RenderPipeline\"=\"UniversalPipeline\" \"UniversalMaterialType\"=\"Lit\" }\n"
                : $"        Tags {{ \"RenderType\"=\"{(g.AlphaClip ? "TransparentCutout" : "Opaque")}\" \"Queue\"=\"{(g.AlphaClip ? "AlphaTest" : "Geometry")}\" \"RenderPipeline\"=\"UniversalPipeline\" \"UniversalMaterialType\"=\"Lit\" }}\n");
            sb.Append("        LOD 300\n\n");
            sb.Append("        Pass\n        {\n            Name \"ForwardLit\"\n            Tags { \"LightMode\"=\"UniversalForward\" }\n");
            sb.Append($"            Cull {(g.DoubleSided ? "Off" : "Back")}\n");
            if (g.Transparent) sb.Append("            Blend SrcAlpha OneMinusSrcAlpha\n            ZWrite Off\n");
            sb.Append(@"
            HLSLPROGRAM
            #pragma target 3.5
            #pragma vertex B2UVert
            #pragma fragment B2UFrag
            #pragma multi_compile _ _MAIN_LIGHT_SHADOWS _MAIN_LIGHT_SHADOWS_CASCADE _MAIN_LIGHT_SHADOWS_SCREEN
            #pragma multi_compile _ _ADDITIONAL_LIGHTS_VERTEX _ADDITIONAL_LIGHTS
            #pragma multi_compile _ _FORWARD_PLUS
            #pragma multi_compile_fragment _ _ADDITIONAL_LIGHT_SHADOWS
            #pragma multi_compile_fragment _ _SHADOWS_SOFT
            #pragma multi_compile_fragment _ _SCREEN_SPACE_OCCLUSION
            #pragma multi_compile _ LIGHTMAP_SHADOW_MIXING
            #pragma multi_compile _ SHADOWS_SHADOWMASK
            #pragma multi_compile _ DIRLIGHTMAP_COMBINED
            #pragma multi_compile _ LIGHTMAP_ON
            #pragma multi_compile_fog
            #pragma multi_compile_instancing

            #include ""Packages/com.unity.render-pipelines.universal/ShaderLibrary/Core.hlsl""
            #include ""Packages/com.unity.render-pipelines.universal/ShaderLibrary/Lighting.hlsl""

");
            foreach (var t in g.Textures)
                sb.Append($"            TEXTURE2D({t.PropertyName}); SAMPLER(sampler{t.PropertyName});\n");
            sb.Append("            CBUFFER_START(UnityPerMaterial)\n");
            foreach (var t in g.Textures) sb.Append($"            float4 {t.PropertyName}_ST;\n");
            sb.Append("            float _Cutoff;\n            CBUFFER_END\n\n");
            sb.Append(Functions(g));
            sb.Append(@"
            struct Attributes
            {
                float4 positionOS : POSITION;
                float3 normalOS   : NORMAL;
                float4 tangentOS  : TANGENT;
                float2 uv0        : TEXCOORD0;
                float2 uv1        : TEXCOORD1;
                UNITY_VERTEX_INPUT_INSTANCE_ID
            };

            struct Varyings
            {
                float4 positionCS : SV_POSITION;
                float4 uv         : TEXCOORD0;
                float3 positionWS : TEXCOORD1;
                float3 normalWS   : TEXCOORD2;
                float4 tangentWS  : TEXCOORD3;
                float3 positionOS : TEXCOORD4;
                half   fogFactor  : TEXCOORD5;
                DECLARE_LIGHTMAP_OR_SH(staticLightmapUV, vertexSH, 6);
                UNITY_VERTEX_INPUT_INSTANCE_ID
            };

            Varyings B2UVert(Attributes v)
            {
                Varyings o = (Varyings)0;
                UNITY_SETUP_INSTANCE_ID(v);
                UNITY_TRANSFER_INSTANCE_ID(v, o);
                VertexPositionInputs pos = GetVertexPositionInputs(v.positionOS.xyz);
                VertexNormalInputs nrm = GetVertexNormalInputs(v.normalOS, v.tangentOS);
                o.positionCS = pos.positionCS;
                o.positionWS = pos.positionWS;
                o.positionOS = v.positionOS.xyz;
                o.normalWS = nrm.normalWS;
                o.tangentWS = float4(nrm.tangentWS, v.tangentOS.w * GetOddNegativeScale());
                o.uv = float4(v.uv0, v.uv1);
                o.fogFactor = ComputeFogFactor(pos.positionCS.z);
                OUTPUT_LIGHTMAP_UV(v.uv1, unity_LightmapST, o.staticLightmapUV);
                OUTPUT_SH(o.normalWS, o.vertexSH);
                return o;
            }

            half4 B2UFrag(Varyings i, FRONT_FACE_TYPE face : FRONT_FACE_SEMANTIC) : SV_Target
            {
                UNITY_SETUP_INSTANCE_ID(i);
                float faceSign = IS_FRONT_VFACE(face, 1.0, -1.0);
                float3 geoN = normalize(i.normalWS);
                float3 b2u_normalWS = geoN * faceSign;
                float3 b2u_tangentWS = normalize(i.tangentWS.xyz);
                float3 b2u_bitangentWS = cross(geoN, b2u_tangentWS) * i.tangentWS.w;
                float3 b2u_positionWS = i.positionWS;
                float3 b2u_positionOS = i.positionOS;
                float3 b2u_viewWS = GetWorldSpaceNormalizeViewDir(i.positionWS);
                float3 b2u_uv0 = float3(i.uv.xy, 0.0);
                float3 b2u_uv1 = float3(i.uv.zw, 0.0);

");
            sb.Append(GraphCode(g, (t, uv) => $"SAMPLE_TEXTURE2D({t.PropertyName}, sampler{t.PropertyName}, {uv})", "                "));
            sb.Append($@"
                float alpha = {Var(s, "Alpha")};
");
            if (g.AlphaClip) sb.Append("                clip(alpha - _Cutoff);\n");
            sb.Append($@"
                InputData inputData = (InputData)0;
                inputData.positionWS = i.positionWS;
                inputData.positionCS = i.positionCS;
                inputData.normalWS = NormalizeNormalPerPixel({Var(s, "NormalWS")});
                inputData.viewDirectionWS = b2u_viewWS;
                inputData.shadowCoord = TransformWorldToShadowCoord(i.positionWS);
                inputData.fogCoord = i.fogFactor;
                inputData.bakedGI = SAMPLE_GI(i.staticLightmapUV, i.vertexSH, inputData.normalWS);
                inputData.normalizedScreenSpaceUV = GetNormalizedScreenSpaceUV(i.positionCS);
                inputData.shadowMask = SAMPLE_SHADOWMASK(i.staticLightmapUV);

                SurfaceData surf = (SurfaceData)0;
                surf.albedo = {Var(s, "BaseColor")};
                surf.metallic = {Var(s, "Metallic")};
                surf.smoothness = {Var(s, "Smoothness")};
                surf.normalTS = half3(0.0, 0.0, 1.0);
                surf.emission = {Var(s, "Emission")};
                surf.occlusion = 1.0;
                surf.specular = half3(0.0, 0.0, 0.0);
                surf.alpha = {(g.Transparent ? "alpha" : "1.0")};

                half4 color = UniversalFragmentPBR(inputData, surf);
                color.rgb = MixFog(color.rgb, inputData.fogCoord);
                color.a = {(g.Transparent ? "alpha" : "1.0")};
                return color;
            }}
            ENDHLSL
        }}

        UsePass ""Universal Render Pipeline/Lit/SHADOWCASTER""
        UsePass ""Universal Render Pipeline/Lit/DEPTHONLY""
        UsePass ""Universal Render Pipeline/Lit/DEPTHNORMALS""
    }}
    FallBack ""Hidden/Universal Render Pipeline/FallbackError""
}}
");
            return sb.ToString();
        }

        // ------------------------------------------------------------------------------
        // Built-in (surface shader)
        // ------------------------------------------------------------------------------

        static string WriteBuiltIn(IRGraph g, string shaderName)
        {
            var s = g.Surface;
            var sb = new StringBuilder();
            sb.Append($"// Generated by Blender to Unity Shader Converter from material '{g.MaterialName}'.\n");
            sb.Append("// Target: Built-in Render Pipeline (surface shader).\n");
            sb.Append($"Shader \"{Escape(shaderName)}\"\n{{\n    Properties\n    {{\n");
            sb.Append(Properties(g));
            sb.Append("    }\n    SubShader\n    {\n");
            sb.Append(g.Transparent
                ? "        Tags { \"RenderType\"=\"Transparent\" \"Queue\"=\"Transparent\" }\n"
                : g.AlphaClip
                    ? "        Tags { \"RenderType\"=\"TransparentCutout\" \"Queue\"=\"AlphaTest\" }\n"
                    : "        Tags { \"RenderType\"=\"Opaque\" \"Queue\"=\"Geometry\" }\n");
            sb.Append("        LOD 300\n");
            sb.Append($"        Cull {(g.DoubleSided ? "Off" : "Back")}\n\n");
            sb.Append("        CGPROGRAM\n");
            sb.Append("        #pragma surface B2USurf Standard fullforwardshadows vertex:B2UVert addshadow");
            if (g.Transparent) sb.Append(" alpha:fade");
            sb.Append('\n');
            sb.Append("        #pragma target 3.5\n\n");
            foreach (var t in g.Textures) sb.Append($"        UNITY_DECLARE_TEX2D({t.PropertyName});\n");
            sb.Append("        float _Cutoff;\n\n");
            sb.Append(Functions(g));
            sb.Append(@"
        struct Input
        {
            float4 b2uUV;
            float3 b2uNormalWS;
            float4 b2uTangentWS;
            float3 b2uPositionOS;
            float3 worldPos;
            float facing : VFACE;
        };

        void B2UVert(inout appdata_full v, out Input o)
        {
            UNITY_INITIALIZE_OUTPUT(Input, o);
            o.b2uUV = float4(v.texcoord.xy, v.texcoord1.xy);
            o.b2uNormalWS = UnityObjectToWorldNormal(v.normal);
            o.b2uTangentWS = float4(UnityObjectToWorldDir(v.tangent.xyz), v.tangent.w * unity_WorldTransformParams.w);
            o.b2uPositionOS = v.vertex.xyz;
        }

        void B2USurf(Input IN, inout SurfaceOutputStandard o)
        {
            float faceSign = IN.facing > 0 ? 1.0 : -1.0;
            float3 geoN = normalize(IN.b2uNormalWS);
            float3 b2u_tangentWS = normalize(IN.b2uTangentWS.xyz);
            float3 b2u_bitangentWS = cross(geoN, b2u_tangentWS) * IN.b2uTangentWS.w;
            float3 b2u_normalWS = geoN * faceSign;
            float3 b2u_positionWS = IN.worldPos;
            float3 b2u_positionOS = IN.b2uPositionOS;
            float3 b2u_viewWS = normalize(UnityWorldSpaceViewDir(IN.worldPos));
            float3 b2u_uv0 = float3(IN.b2uUV.xy, 0.0);
            float3 b2u_uv1 = float3(IN.b2uUV.zw, 0.0);

");
            sb.Append(GraphCode(g, (t, uv) => $"UNITY_SAMPLE_TEX2D({t.PropertyName}, {uv})", "            "));
            sb.Append($@"
            float alpha = {Var(s, "Alpha")};
");
            if (g.AlphaClip) sb.Append("            clip(alpha - _Cutoff);\n");
            sb.Append($@"            float3 nWS = {Var(s, "NormalWS")};
            // Surface shaders expect a tangent space normal.
            o.Normal = normalize(float3(dot(nWS, b2u_tangentWS), dot(nWS, b2u_bitangentWS), dot(nWS, geoN)));
            o.Albedo = {Var(s, "BaseColor")};
            o.Metallic = {Var(s, "Metallic")};
            o.Smoothness = {Var(s, "Smoothness")};
            o.Emission = {Var(s, "Emission")};
            o.Occlusion = 1.0;
            o.Alpha = alpha;
        }}
        ENDCG
    }}
    FallBack ""Standard""
}}
");
            return sb.ToString();
        }
    }
}

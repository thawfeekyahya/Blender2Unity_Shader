using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace B2U
{
    public enum GraphTarget { URP, BuiltIn }

    /// <summary>
    /// Writes a Shader Graph (.shadergraph, multi-JSON format, Shader Graph 12+) from an <see cref="IRGraph"/>.
    ///
    /// Textures and mesh inputs (UV, normal, view direction...) become native Shader Graph nodes;
    /// every other Blender node becomes a Custom Function node (File mode) whose function lives in a
    /// generated per-material .hlsl include (see <see cref="WriteInclude"/>).
    /// </summary>
    public sealed class ShaderGraphWriter
    {
        const string SG = "UnityEditor.ShaderGraph.";
        const int StageAll = 3, StageVertex = 1, StageFragment = 2;

        readonly IRGraph _g;
        readonly GraphTarget _target;
        readonly string _includeGuid;
        readonly Func<IRTexture, string> _textureGuid;

        readonly List<JObj> _objects = new List<JObj>();
        readonly List<object> _nodeRefs = new List<object>();
        readonly List<object> _edges = new List<object>();
        readonly List<object> _propertyRefs = new List<object>();
        readonly Dictionary<IRNode, string> _nodeIds = new Dictionary<IRNode, string>();
        readonly Dictionary<IRNode, Dictionary<string, int>> _inSlots = new Dictionary<IRNode, Dictionary<string, int>>();
        readonly Dictionary<IRNode, Dictionary<string, int>> _outSlots = new Dictionary<IRNode, Dictionary<string, int>>();
        readonly Dictionary<ImplicitInput, (string node, int slot)> _implicitNodes = new Dictionary<ImplicitInput, (string, int)>();
        readonly Dictionary<IRTexture, string> _texProps = new Dictionary<IRTexture, string>();
        int _implicitRow;
        int _maxDepth;

        /// <summary>Folder shown in the material shader dropdown (graph file name is appended by Unity).</summary>
        public string GraphPath = "Blender";

        public ShaderGraphWriter(IRGraph g, GraphTarget target, string includeGuid, Func<IRTexture, string> textureGuid)
        {
            _g = g;
            _target = target;
            _includeGuid = includeGuid;
            _textureGuid = textureGuid;
        }

        /// <summary>The .hlsl include holding helpers and one function per Custom Function node.</summary>
        public static string WriteInclude(IRGraph g)
        {
            var guard = "B2U_" + Hlsl.Identifier(g.MaterialName).ToUpperInvariant() + "_INCLUDED";
            var sb = new StringBuilder();
            sb.Append($"// Generated by Blender to Unity Shader Converter for material '{g.MaterialName}'.\n");
            sb.Append($"#ifndef {guard}\n#define {guard}\n\n");
            sb.Append(HlslLibrary.Common).Append('\n');
            foreach (var n in g.Ordered())
                if (n.Kind == IRNodeKind.Function)
                {
                    sb.Append(Hlsl.FunctionDefinition(n, "_float")).Append('\n');
                    // Half precision graphs call the _half variant; route it to the float version.
                    sb.Append($"#define {n.FunctionName}_half {n.FunctionName}_float\n\n");
                }
            sb.Append("#endif\n");
            return sb.ToString();
        }

        public string Write()
        {
            var graphId = NewId();
            var depths = _g.Depths();
            _maxDepth = depths.Values.DefaultIfEmpty(0).Max();
            var columnCounts = new Dictionary<int, int>();

            foreach (var n in _g.Ordered())
            {
                var d = depths.TryGetValue(n, out var dd) ? dd : 0;
                columnCounts.TryGetValue(d, out var row);
                columnCounts[d] = row + 1;
                var x = -420f - d * 380f;
                var y = row * 260f - 200f;
                if (n.Kind == IRNodeKind.Texture) EmitTexture(n, x, y);
                else EmitFunction(n, x, y);
            }

            // Wire up IR links and implicit inputs.
            foreach (var n in _g.Ordered())
            {
                var slots = _inSlots[n];
                foreach (var i in n.Inputs)
                {
                    if (!slots.TryGetValue(i.Name, out var slot)) continue;
                    if (i.Link != null)
                        Edge(_nodeIds[i.Link.Node], _outSlots[i.Link.Node][i.Link.Port], _nodeIds[n], slot);
                    else if (i.Implicit != ImplicitInput.None)
                    {
                        // Sample Texture 2D already defaults to UV0.
                        if (n.Kind == IRNodeKind.Texture && i.Implicit == ImplicitInput.UV0) continue;
                        var src = ImplicitNode(i.Implicit);
                        Edge(src.node, src.slot, _nodeIds[n], slot);
                    }
                }
            }

            var (vertexBlocks, fragmentBlocks) = EmitBlocks();
            var targetId = EmitTarget();

            var category = new JObj
            {
                { "m_SGVersion", 0 }, { "m_Type", SG + "CategoryData" }, { "m_ObjectId", NewId() },
                { "m_Name", "" }, { "m_ChildObjectList", _propertyRefs },
            };

            var graph = new JObj
            {
                { "m_SGVersion", 3 },
                { "m_Type", SG + "GraphData" },
                { "m_ObjectId", graphId },
                { "m_Properties", _propertyRefs },
                { "m_Keywords", new object[0] },
                { "m_Dropdowns", new object[0] },
                { "m_CategoryData", new object[] { Ref((string)category["m_ObjectId"]) } },
                { "m_Nodes", _nodeRefs },
                { "m_GroupDatas", new object[0] },
                { "m_StickyNoteDatas", new object[0] },
                { "m_Edges", _edges },
                { "m_VertexContext", new JObj { { "m_Position", Vec2(0, 0) }, { "m_Blocks", vertexBlocks } } },
                { "m_FragmentContext", new JObj { { "m_Position", Vec2(0, 220) }, { "m_Blocks", fragmentBlocks } } },
                { "m_PreviewData", new JObj {
                    { "serializedMesh", new JObj { { "m_SerializedMesh", "{\"mesh\":{\"instanceID\":0}}" }, { "m_Guid", "" } } },
                    { "preventRotation", false } } },
                { "m_Path", GraphPath },
                { "m_GraphPrecision", 1 },
                { "m_PreviewMode", 2 },
                { "m_OutputNode", Ref("") },
                { "m_SubDatas", new object[0] },
                { "m_ActiveTargets", new object[] { Ref(targetId) } },
            };

            var sb = new StringBuilder();
            sb.Append(JsonWriter.Write(graph)).Append("\n\n");
            sb.Append(JsonWriter.Write(category)).Append("\n\n");
            foreach (var o in _objects) sb.Append(JsonWriter.Write(o)).Append("\n\n");
            return sb.ToString();
        }

        // ------------------------------------------------------------------------------
        // Helpers
        // ------------------------------------------------------------------------------

        static string NewId() => Guid.NewGuid().ToString("N");
        static JObj Ref(string id) => new JObj { { "m_Id", id } };
        static JObj Vec2(float x, float y) => new JObj { { "x", x }, { "y", y } };
        static JObj Vec3(float x, float y, float z) => new JObj { { "x", x }, { "y", y }, { "z", z } };
        static JObj Vec4(float x, float y, float z, float w) => new JObj { { "x", x }, { "y", y }, { "z", z }, { "w", w } };

        void Edge(string fromNode, int fromSlot, string toNode, int toSlot)
        {
            _edges.Add(new JObj
            {
                { "m_OutputSlot", new JObj { { "m_Node", Ref(fromNode) }, { "m_SlotId", fromSlot } } },
                { "m_InputSlot", new JObj { { "m_Node", Ref(toNode) }, { "m_SlotId", toSlot } } },
            });
        }

        JObj NodeBase(string type, string name, float x, float y, List<object> slotRefs, int sgVersion = 0)
        {
            var id = NewId();
            var o = new JObj
            {
                { "m_SGVersion", sgVersion },
                { "m_Type", type },
                { "m_ObjectId", id },
                { "m_Group", Ref("") },
                { "m_Name", name },
                { "m_DrawState", new JObj {
                    { "m_Expanded", true },
                    { "m_Position", new JObj { { "serializedVersion", "2" }, { "x", x }, { "y", y }, { "width", 0f }, { "height", 0f } } } } },
                { "m_Slots", slotRefs },
                { "synonyms", new object[0] },
                { "m_Precision", 0 },
                { "m_PreviewExpanded", false },
                { "m_DismissedVersion", 0 },
                { "m_PreviewMode", 0 },
                { "m_CustomColors", new JObj { { "m_SerializableColors", new object[0] } } },
            };
            _objects.Add(o);
            _nodeRefs.Add(Ref(id));
            return o;
        }

        /// <summary>Create a slot object and return a reference to it.</summary>
        JObj Slot(string type, int id, string displayName, bool output, int stage, Action<JObj> extra = null, string shaderName = null)
        {
            var o = new JObj
            {
                { "m_SGVersion", 0 },
                { "m_Type", SG + type },
                { "m_ObjectId", NewId() },
                { "m_Id", id },
                { "m_DisplayName", displayName },
                { "m_SlotType", output ? 1 : 0 },
                { "m_Hidden", false },
                { "m_ShaderOutputName", shaderName ?? displayName },
                { "m_StageCapability", stage },
            };
            extra?.Invoke(o);
            _objects.Add(o);
            return Ref((string)o["m_ObjectId"]);
        }

        JObj ValueSlot(PortType t, int id, string name, bool output, float[] v, int stage = StageAll)
        {
            float C(int i) => v != null && i < v.Length ? v[i] : 0f;
            switch (t)
            {
                case PortType.Float:
                    return Slot("Vector1MaterialSlot", id, name, output, stage, o =>
                    { o.Add("m_Value", C(0)); o.Add("m_DefaultValue", C(0)); o.Add("m_Labels", new object[0]); });
                case PortType.Float2:
                    return Slot("Vector2MaterialSlot", id, name, output, stage, o =>
                    { o.Add("m_Value", Vec2(C(0), C(1))); o.Add("m_DefaultValue", Vec2(C(0), C(1))); o.Add("m_Labels", new object[0]); });
                case PortType.Float3:
                    return Slot("Vector3MaterialSlot", id, name, output, stage, o =>
                    { o.Add("m_Value", Vec3(C(0), C(1), C(2))); o.Add("m_DefaultValue", Vec3(C(0), C(1), C(2))); o.Add("m_Labels", new object[0]); });
                default:
                    return Slot("Vector4MaterialSlot", id, name, output, stage, o =>
                    { o.Add("m_Value", Vec4(C(0), C(1), C(2), C(3))); o.Add("m_DefaultValue", Vec4(C(0), C(1), C(2), C(3))); o.Add("m_Labels", new object[0]); });
            }
        }

        // ------------------------------------------------------------------------------
        // Nodes
        // ------------------------------------------------------------------------------

        void EmitFunction(IRNode n, float x, float y)
        {
            var slots = new List<object>();
            var ins = new Dictionary<string, int>();
            var outs = new Dictionary<string, int>();
            int id = 0;
            foreach (var i in n.Inputs)
            {
                ins[i.Name] = id;
                slots.Add(ValueSlot(i.Type, id++, i.Name, false, i.IsConstant ? i.Constant : null));
            }
            foreach (var o in n.Outputs)
            {
                outs[o.Name] = id;
                slots.Add(ValueSlot(o.Type, id++, o.Name, true, null));
            }
            var node = NodeBase(SG + "CustomFunctionNode", n.Title, x, y, slots, sgVersion: 1);
            node.Add("m_SourceType", 0); // File
            node.Add("m_FunctionName", n.FunctionName);
            node.Add("m_FunctionSource", _includeGuid);
            node.Add("m_FunctionSourceUsePragmas", true);
            node.Add("m_FunctionBody", "");
            _nodeIds[n] = (string)node["m_ObjectId"];
            _inSlots[n] = ins;
            _outSlots[n] = outs;
        }

        void EmitTexture(IRNode n, float x, float y)
        {
            var tex = n.Texture;
            var propId = TextureProperty(tex);

            // Property node feeding the texture slot.
            var propSlots = new List<object>
            {
                Slot("Texture2DMaterialSlot", 0, "Out", true, StageAll, o => o.Add("m_BareResource", false)),
            };
            var propNode = NodeBase(SG + "PropertyNode", "Property", x - 260f, y, propSlots);
            propNode.Add("m_Property", Ref(propId));

            var slots = new List<object>
            {
                ValueSlot(PortType.Float4, 0, "RGBA", true, null, StageFragment),
                ValueSlot(PortType.Float, 4, "R", true, null, StageFragment),
                ValueSlot(PortType.Float, 5, "G", true, null, StageFragment),
                ValueSlot(PortType.Float, 6, "B", true, null, StageFragment),
                ValueSlot(PortType.Float, 7, "A", true, null, StageFragment),
                Slot("Texture2DInputMaterialSlot", 1, "Texture", false, StageAll, o =>
                {
                    o.Add("m_BareResource", false);
                    o.Add("m_Texture", new JObj { { "m_SerializedTexture", "{\"texture\":{\"instanceID\":0}}" }, { "m_Guid", "" } });
                    o.Add("m_DefaultType", 0);
                }),
                Slot("UVMaterialSlot", 2, "UV", false, StageAll, o =>
                {
                    o.Add("m_Value", Vec2(0, 0)); o.Add("m_DefaultValue", Vec2(0, 0));
                    o.Add("m_Labels", new object[0]); o.Add("m_Channel", 0);
                }),
                Slot("SamplerStateMaterialSlot", 3, "Sampler", false, StageAll, o => o.Add("m_BareResource", false)),
            };
            var node = NodeBase(SG + "SampleTexture2DNode", "Sample Texture 2D", x, y, slots);
            node.Add("m_TextureType", 0);
            node.Add("m_NormalMapSpace", 0);
            node.Add("m_EnableGlobalMipBias", true);
            node.Add("m_MipSamplingMode", 0);

            var nodeId = (string)node["m_ObjectId"];
            Edge((string)propNode["m_ObjectId"], 0, nodeId, 1);
            _nodeIds[n] = nodeId;
            _inSlots[n] = new Dictionary<string, int> { { "UV", 2 } };
            _outSlots[n] = new Dictionary<string, int> { { "Color", 0 }, { "Alpha", 7 } };
        }

        string TextureProperty(IRTexture tex)
        {
            if (_texProps.TryGetValue(tex, out var existing)) return existing;
            var guid = _textureGuid?.Invoke(tex) ?? "";
            var serialized = string.IsNullOrEmpty(guid)
                ? "{\"texture\":{\"instanceID\":0}}"
                : "{\"texture\":{\"fileID\":2800000,\"guid\":\"" + guid + "\",\"type\":3}}";
            var id = NewId();
            var prop = new JObj
            {
                { "m_SGVersion", 0 },
                { "m_Type", SG + "Internal.Texture2DShaderProperty" },
                { "m_ObjectId", id },
                { "m_Guid", new JObj { { "m_GuidSerialized", Guid.NewGuid().ToString() } } },
                { "m_Name", tex.DisplayName },
                { "m_DefaultRefNameVersion", 1 },
                { "m_RefNameGeneratedByDisplayName", "" },
                { "m_DefaultReferenceName", tex.PropertyName },
                { "m_OverrideReferenceName", tex.PropertyName },
                { "m_GeneratePropertyBlock", true },
                { "m_UseCustomSlotLabel", false },
                { "m_CustomSlotLabel", "" },
                { "m_DismissedVersion", 0 },
                { "m_Precision", 0 },
                { "overrideHLSLDeclaration", false },
                { "hlslDeclarationOverride", 0 },
                { "m_Hidden", false },
                { "m_Value", new JObj { { "m_SerializedTexture", serialized }, { "m_Guid", "" } } },
                { "isMainTexture", false },
                { "useTilingAndOffset", false },
                { "m_Modifiable", true },
                { "m_DefaultType", 0 },
            };
            _objects.Add(prop);
            _propertyRefs.Add(Ref(id));
            _texProps[tex] = id;
            return id;
        }

        (string node, int slot) ImplicitNode(ImplicitInput imp)
        {
            if (_implicitNodes.TryGetValue(imp, out var existing)) return existing;
            var x = -420f - (_maxDepth + 1) * 380f;
            var y = _implicitRow++ * 140f - 200f;
            JObj node;
            switch (imp)
            {
                case ImplicitInput.UV0:
                case ImplicitInput.UV1:
                    node = NodeBase(SG + "UVNode", "UV", x, y,
                        new List<object> { ValueSlot(PortType.Float4, 0, "Out", true, null) });
                    node.Add("m_OutputChannel", imp == ImplicitInput.UV1 ? 1 : 0);
                    break;
                case ImplicitInput.NormalWS:
                    node = SpaceNode("NormalVectorNode", "Normal Vector", x, y, 2);
                    break;
                case ImplicitInput.TangentWS:
                    node = SpaceNode("TangentVectorNode", "Tangent Vector", x, y, 2);
                    break;
                case ImplicitInput.BitangentWS:
                    node = SpaceNode("BitangentVectorNode", "Bitangent Vector", x, y, 2);
                    break;
                case ImplicitInput.ViewDirWS:
                    node = SpaceNode("ViewDirectionNode", "View Direction", x, y, 2);
                    break;
                case ImplicitInput.PositionWS:
                    node = SpaceNode("PositionNode", "Position", x, y, 2);
                    node.Add("m_PositionSource", 0);
                    break;
                default:
                    node = SpaceNode("PositionNode", "Position", x, y, 0);
                    node.Add("m_PositionSource", 0);
                    break;
            }
            var r = ((string)node["m_ObjectId"], 0);
            _implicitNodes[imp] = r;
            return r;
        }

        JObj SpaceNode(string type, string name, float x, float y, int space)
        {
            var node = NodeBase(SG + type, name, x, y,
                new List<object> { ValueSlot(PortType.Float3, 0, "Out", true, null) });
            node.Add("m_Space", space);
            return node;
        }

        // ------------------------------------------------------------------------------
        // Master stack
        // ------------------------------------------------------------------------------

        string Block(string descriptor, float y, JObj slot)
        {
            var node = NodeBase(SG + "BlockNode", descriptor, 0, y, new List<object> { slot });
            node.Add("m_SerializedDescriptor", descriptor);
            return (string)node["m_ObjectId"];
        }

        (List<object> vertex, List<object> fragment) EmitBlocks()
        {
            var vertex = new List<object>
            {
                Ref(Block("VertexDescription.Position", 0, Slot("PositionMaterialSlot", 0, "Position", false, StageVertex, o =>
                    { o.Add("m_Value", Vec3(0, 0, 0)); o.Add("m_DefaultValue", Vec3(0, 0, 0)); o.Add("m_Labels", new object[0]); o.Add("m_Space", 0); }))),
                Ref(Block("VertexDescription.Normal", 0, Slot("NormalMaterialSlot", 0, "Normal", false, StageVertex, o =>
                    { o.Add("m_Value", Vec3(0, 0, 0)); o.Add("m_DefaultValue", Vec3(0, 0, 0)); o.Add("m_Labels", new object[0]); o.Add("m_Space", 0); }))),
                Ref(Block("VertexDescription.Tangent", 0, Slot("TangentMaterialSlot", 0, "Tangent", false, StageVertex, o =>
                    { o.Add("m_Value", Vec3(0, 0, 0)); o.Add("m_DefaultValue", Vec3(0, 0, 0)); o.Add("m_Labels", new object[0]); o.Add("m_Space", 0); }))),
            };

            var s = _g.Surface;
            var sId = _nodeIds[s];
            var so = _outSlots[s];
            var fragment = new List<object>();

            void Connected(string descriptor, string port, JObj slot)
            {
                var id = Block(descriptor, 0, slot);
                fragment.Add(Ref(id));
                if (port != null) Edge(sId, so[port], id, 0);
            }

            Connected("SurfaceDescription.BaseColor", "BaseColor", Slot("ColorRGBMaterialSlot", 0, "Base Color", false, StageFragment, o =>
            {
                o.Add("m_Value", Vec3(0.5f, 0.5f, 0.5f)); o.Add("m_DefaultValue", Vec3(0.5f, 0.5f, 0.5f));
                o.Add("m_Labels", new object[0]); o.Add("m_ColorMode", 0);
                o.Add("m_DefaultColor", new JObj { { "r", 0.5f }, { "g", 0.5f }, { "b", 0.5f }, { "a", 1f } });
            }, "BaseColor"));
            Connected("SurfaceDescription.NormalWS", "NormalWS", Slot("NormalMaterialSlot", 0, "Normal (World Space)", false, StageFragment, o =>
                { o.Add("m_Value", Vec3(0, 0, 0)); o.Add("m_DefaultValue", Vec3(0, 0, 0)); o.Add("m_Labels", new object[0]); o.Add("m_Space", 2); }, "NormalWS"));
            Connected("SurfaceDescription.Metallic", "Metallic", FloatBlockSlot("Metallic", "Metallic", 0f));
            Connected("SurfaceDescription.Smoothness", "Smoothness", FloatBlockSlot("Smoothness", "Smoothness", 0.5f));
            Connected("SurfaceDescription.Emission", "Emission", Slot("ColorRGBMaterialSlot", 0, "Emission", false, StageFragment, o =>
            {
                o.Add("m_Value", Vec3(0, 0, 0)); o.Add("m_DefaultValue", Vec3(0, 0, 0));
                o.Add("m_Labels", new object[0]); o.Add("m_ColorMode", 1);
                o.Add("m_DefaultColor", new JObj { { "r", 0f }, { "g", 0f }, { "b", 0f }, { "a", 1f } });
            }, "Emission"));
            Connected("SurfaceDescription.Occlusion", null, FloatBlockSlot("Ambient Occlusion", "Occlusion", 1f));
            if (_g.Transparent || _g.AlphaClip)
                Connected("SurfaceDescription.Alpha", "Alpha", FloatBlockSlot("Alpha", "Alpha", 1f));
            if (_g.AlphaClip)
                Connected("SurfaceDescription.AlphaClipThreshold", null, FloatBlockSlot("Alpha Clip Threshold", "AlphaClipThreshold", _g.AlphaThreshold));
            return (vertex, fragment);
        }

        JObj FloatBlockSlot(string display, string shaderName, float value) =>
            Slot("Vector1MaterialSlot", 0, display, false, StageFragment, o =>
            { o.Add("m_Value", value); o.Add("m_DefaultValue", value); o.Add("m_Labels", new object[0]); }, shaderName);

        string EmitTarget()
        {
            var subId = NewId();
            var targetId = NewId();
            var renderFace = _g.DoubleSided ? 0 : 2; // Both : Front
            if (_target == GraphTarget.URP)
            {
                _objects.Add(new JObj
                {
                    { "m_SGVersion", 2 },
                    { "m_Type", "UnityEditor.Rendering.Universal.ShaderGraph.UniversalLitSubTarget" },
                    { "m_ObjectId", subId },
                    { "m_WorkflowMode", 1 },
                    { "m_NormalDropOffSpace", 2 },
                    { "m_ClearCoat", false },
                    { "m_BlendModePreserveSpecular", true },
                });
                _objects.Add(new JObj
                {
                    { "m_SGVersion", 1 },
                    { "m_Type", "UnityEditor.Rendering.Universal.ShaderGraph.UniversalTarget" },
                    { "m_ObjectId", targetId },
                    { "m_Datas", new object[0] },
                    { "m_ActiveSubTarget", Ref(subId) },
                    { "m_AllowMaterialOverride", false },
                    { "m_SurfaceType", _g.Transparent ? 1 : 0 },
                    { "m_ZTestMode", 4 },
                    { "m_ZWriteControl", 0 },
                    { "m_AlphaMode", 0 },
                    { "m_RenderFace", renderFace },
                    { "m_AlphaClip", _g.AlphaClip },
                    { "m_CastShadows", true },
                    { "m_ReceiveShadows", true },
                    { "m_SupportsLODCrossFade", false },
                    { "m_CustomEditorGUI", "" },
                    { "m_SupportVFX", false },
                });
            }
            else
            {
                _objects.Add(new JObj
                {
                    { "m_SGVersion", 0 },
                    { "m_Type", "UnityEditor.Rendering.BuiltIn.ShaderGraph.BuiltInLitSubTarget" },
                    { "m_ObjectId", subId },
                    { "m_WorkflowMode", 1 },
                    { "m_NormalDropOffSpace", 2 },
                });
                _objects.Add(new JObj
                {
                    { "m_SGVersion", 0 },
                    { "m_Type", "UnityEditor.Rendering.BuiltIn.ShaderGraph.BuiltInTarget" },
                    { "m_ObjectId", targetId },
                    { "m_ActiveSubTarget", Ref(subId) },
                    { "m_AllowMaterialOverride", false },
                    { "m_SurfaceType", _g.Transparent ? 1 : 0 },
                    { "m_ZWriteControl", 0 },
                    { "m_ZTestMode", 4 },
                    { "m_AlphaMode", 0 },
                    { "m_RenderFace", renderFace },
                    { "m_AlphaClip", _g.AlphaClip },
                    { "m_CustomEditorGUI", "" },
                });
            }
            return targetId;
        }
    }
